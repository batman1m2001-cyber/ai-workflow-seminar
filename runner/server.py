"""The seminar's local runner.

    uv run python -m runner.server            # http://127.0.0.1:8000

One process, three jobs:

| path | does |
|---|---|
| `/` | serves the site (`site/`) |
| `/api/run` | runs a playground's code in this project's venv — real operonx, real openai SDK |
| `/mock/v1/...` | an OpenAI-compatible mock model (`site/assets/py/mockllm.py`), so every playground runs with no key |

Mode `mock` points the code's `OPENAI_BASE_URL` at `/mock/v1`; mode `real`
uses `OPENAI_API_KEY` / `OPENAI_BASE_URL` / `SEMINAR_MODEL` from `.env`.
The key never reaches the browser. Bound to 127.0.0.1: it runs whatever
code it is sent, so it must never listen on a network.
"""
from __future__ import annotations

import os
import subprocess
import sys
import time
import uuid
from pathlib import Path

from dotenv import dotenv_values
from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse, RedirectResponse, Response
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
RUNS = ROOT / "playground" / "runs"
PORT = int(os.environ.get("SEMINAR_PORT", "8000"))
TIMEOUT_S = 90

sys.path.insert(0, str(SITE / "assets" / "py"))
import mockllm  # noqa: E402


def write_bundle() -> None:
    """The browser runtime's Python, as a script tag can load it — `fetch` is
    blocked when the site is opened as files."""
    import json
    py = SITE / "assets" / "py"
    src = {"mockllm": (py / "mockllm.py").read_text(encoding="utf-8"),
           "openai": (py / "openai_shim.py").read_text(encoding="utf-8")}
    header = "// generated by runner/server.py from mockllm.py + openai_shim.py"
    (py / "bundle.js").write_text(header + "\nwindow.SEMINAR_PY = " + json.dumps(src) + ";\n", encoding="utf-8")


write_bundle()

app = FastAPI(title="ai-workflow-seminar runner")


def _real() -> dict:
    env = {**dotenv_values(ROOT / ".env"), **{k: v for k, v in os.environ.items() if k.startswith(("OPENAI_", "SEMINAR_"))}}
    return {k: v for k, v in env.items() if v}


